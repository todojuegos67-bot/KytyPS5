import json,sys
root=sys.argv[1]
def cmd(c):
    c=list(c); i=c.index('--vblank-frequency'); del c[i:i+2]; return c
base=json.load(open(root+'/config/sin-fg.json'))
be=base['environment']
modes=[('sin-fg','Sin frame generation','sin-fg.json'),
('amd-x2','AMD x2','fsr3.json'),('amd-x3','AMD x3','fsr3-x3.json'),('amd-x4','AMD x4','fsr3-x4.json'),
('amd-120','120 FPS AMD Smooth Souls','fsr3-x3-120.json'),('amd-dinamico','AMD MFG dinamico (x2-x4)','fsr3-mfg-dynamic.json'),
('dlss-x2','DLSS x2','dlss-x2.json'),('dlss-x3','DLSS x3','dlss-x3.json'),('dlss-x4','DLSS x4','dlss-x4.json'),
('dlss-x5','200 FPS Nvidia Smooth x5','dlss-x5.json'),('dlss-x6','216 FPS Nvidia Smooth x6','dlss-x6.json'),
('dlss-120','120 FPS Nvidia Smooth Souls','dlss-x3-120.json'),('dlss-dinamico','DLSS MFG dinamico (x2-x4)','dlss-dynamic.json')]
out=["// Generated by tools/port/gen-tables.py from config/*.json (the launcher's frame generation configs): the common",
"// switches (config/sin-fg.json's environment) and what each mode's config adds or changes. Regenerate when they change.",
'#pragma once','','namespace Port::Tables {','struct Pair { const char* key; const char* value; };','inline constexpr Pair kBaseEnv[] = {']
for k,v in be.items(): out.append(f'\t{{"{k}", "{v}"}},')
out.append('};')
out.append('struct FgMode { const char* id; const char* label; const char* config; const Pair* env; int env_count; };')
rows=[]
for mid,label,f in modes:
    j=json.load(open(root+'/config/'+f)); e=j['environment']
    assert cmd(j['command'])==cmd(base['command']), f
    assert all(k in e for k in be), f
    d={k:v for k,v in e.items() if be.get(k)!=v}
    name='k'+''.join(p.capitalize() for p in mid.replace('-',' ').split())
    out.append(f'inline constexpr Pair {name}[] = {{' + ', '.join(f'{{"{k}", "{v}"}}' for k,v in d.items()) + (', ' if d else '') + '{nullptr, nullptr}};')
    rows.append(f'\t{{"{mid}", "{label}", "{f}", {name}, {len(d)}}},')
out.append('inline constexpr FgMode kFgModes[] = {'); out+=rows; out.append('};')
out.append('} // namespace Port::Tables')
open(root+'/src/port/ds-tables.h','w').write('\n'.join(out)+'\n')
