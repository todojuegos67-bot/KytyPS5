#!/usr/bin/env python3
"""Compiles src/shaders/*.comp with glslangValidator and writes src/shaders/<name>_spv.h (a uint32_t array).

The generated headers are committed (CI has no shader compiler); run this after changing a shader:
    python3 tools/embed_spv.py [path/to/glslangValidator]
"""
import pathlib, subprocess, sys, tempfile

root = pathlib.Path(__file__).resolve().parent.parent / "src" / "shaders"
glslang = sys.argv[1] if len(sys.argv) > 1 else "glslangValidator"
version = subprocess.run([glslang, "--version"], capture_output=True, text=True).stdout.splitlines()[0]
for src in sorted(root.glob("*.comp")):
    with tempfile.TemporaryDirectory() as tmp:
        spv = pathlib.Path(tmp) / "out.spv"
        subprocess.run([glslang, "-V", "--target-env", "vulkan1.3", "-o", str(spv), str(src)], check=True,
                       capture_output=True)
        data = spv.read_bytes()
    words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
    symbol = src.stem.upper() + "_SPV"
    lines = [f"// Generated by tools/embed_spv.py from {src.name} ({version}). Do not edit.", "#pragma once",
             "#include <cstdint>", f"inline constexpr uint32_t {symbol}[] = {{"]
    for i in range(0, len(words), 8):
        lines.append("\t" + ", ".join(f"0x{w:08x}u" for w in words[i:i + 8]) + ",")
    lines.append("};")
    (root / f"{src.stem}_spv.h").write_text("\n".join(lines) + "\n")
    print(f"{src.name}: {len(data)} bytes -> {src.stem}_spv.h")
